import Foundation

/// W17: which files are screenshots, where macOS saves them, which clipboard content is an image.
/// Pure logic (no AppKit, no file system), unit-tested; ScreenshotSource does the watching.
public enum ShotFiles {
    /// macOS names: "Screenshot 2026-10-20 at 18.13.03.png" (en), "Capture d’écran 2026-10-20 à 18.13.03.png"
    /// (fr, typographic apostrophe; the straight one is accepted too).
    public static let defaultPrefixes = ["Screenshot ", "Capture d’écran ", "Capture d'écran "]
    public static let extensions: Set<String> = ["png", "jpg", "jpeg", "heic", "tiff", "tif"]

    /// A visible screenshot file: one of the prefixes (or `customName` from `defaults read
    /// com.apple.screencapture name`), an image extension. Hidden files (macOS writes ".Screenshot …" first,
    /// then renames) never match.
    public static func isScreenshot(_ name: String, customName: String? = nil) -> Bool {
        guard !name.hasPrefix("."), let dot = name.lastIndex(of: ".") else { return false }
        guard extensions.contains(name[name.index(after: dot)...].lowercased()) else { return false }
        var prefixes = defaultPrefixes
        if let c = customName?.trimmingCharacters(in: .whitespaces), !c.isEmpty { prefixes.append(c + " ") }
        let n = name.precomposedStringWithCanonicalMapping
        return prefixes.contains { n.hasPrefix($0.precomposedStringWithCanonicalMapping) }
    }

    /// The screenshot folder: `override` ($OI_SHOT_DIR, tests) else `defaults read com.apple.screencapture
    /// location` (~ expanded) when it is an existing directory, else ~/Desktop.
    public static func location(defaultsValue: String?, home: String, override: String? = nil,
                                isDirectory: (String) -> Bool) -> String {
        if let o = override, !o.isEmpty { return (o as NSString).expandingTildeInPath }
        let desktop = home + "/Desktop"
        guard var v = defaultsValue?.trimmingCharacters(in: .whitespacesAndNewlines), !v.isEmpty else { return desktop }
        if v == "~" || v.hasPrefix("~/") { v = home + v.dropFirst() }
        return isDirectory(v) ? v : desktop
    }

    /// New screenshot names in a listing: matching, not seen before.
    public static func newShots(in names: [String], seen: Set<String>, customName: String? = nil) -> [String] {
        names.filter { !seen.contains($0) && isScreenshot($0, customName: customName) }.sorted()
    }
}

/// The clipboard side: an image put on the pasteboard (⌘⇧⌃4, "Copy" in the screenshot thumbnail).
public enum ClipboardShot {
    public static let imageTypes = ["public.png", "public.tiff"]
    /// nspasteboard.org markers for passwords / transient content: such a change is never read.
    public static let privateTypes: Set<String> = ["org.nspasteboard.ConcealedType", "org.nspasteboard.TransientType",
                                                   "org.nspasteboard.AutoGeneratedType"]

    /// The type to read for a change with these `types`, or nil (no image, or marked private).
    public static func imageType(in types: [String]) -> String? {
        guard types.allSatisfy({ !privateTypes.contains($0) }) else { return nil }
        return imageTypes.first { types.contains($0) }
    }

    /// File name for a saved clipboard image: clip-<UTC stamp>.png.
    public static func fileName(at t: Date) -> String {
        let f = DateFormatter()
        f.locale = Locale(identifier: "en_US_POSIX")
        f.timeZone = TimeZone(identifier: "UTC")
        f.dateFormat = "yyyyMMdd'T'HHmmss.SSS'Z'"
        return "clip-\(f.string(from: t)).png"
    }

    /// The oldest files to delete so that at most `keep` remain (names sort by time).
    public static func prune(_ names: [String], keep: Int) -> [String] {
        let clips = names.filter { $0.hasPrefix("clip-") && $0.hasSuffix(".png") }.sorted()
        return clips.count > keep ? Array(clips.prefix(clips.count - keep)) : []
    }
}

/// NSPasteboard.changeCount, polled: a change is reported once.
public struct ChangeCounter: Sendable {
    public private(set) var last: Int?
    public init(_ initial: Int? = nil) { last = initial }

    /// True when `count` differs from the previous poll (the first poll only primes).
    public mutating func changed(_ count: Int) -> Bool {
        defer { last = count }
        guard let l = last else { return false }
        return l != count
    }
}

extension AWEvent {
    /// W17: {"kind": "shot", "src": "file" | "clipboard", "path": <image>}.
    public static func shot(at t: Date, path: String, src: String) -> AWEvent {
        AWEvent(timestamp: t, data: ["kind": .string("shot"), "src": .string(src), "path": .string(path)])
    }
}

/// ("context is state, not timers"): a screenshot is part of the current context exactly
/// while it is LIVE on screen: macOS's floating thumbnail (bottom-right, owned by screencaptureui) or the
/// screenshot / markup window. Pure logic over the on-screen window list (CGWindowListCopyWindowInfo: owner name,
/// layer, bounds in global top-left coordinates), unit-tested; ScreenshotSource polls the list.
public enum ShotWindows {
    public static let owners: Set<String> = ["screencaptureui", "Screenshot"]
    public static let edge: Double = 48           // the thumbnail sits this close to the screen's bottom-right corner
    public static let markupMin = (w: 300.0, h: 200.0)

    public struct Window: Equatable, Sendable {
        public var owner: String
        public var layer: Int
        public var x, y, w, h: Double
        public var alpha: Double
        public init(owner: String, layer: Int = 0, x: Double, y: Double, w: Double, h: Double, alpha: Double = 1) {
            self.owner = owner; self.layer = layer; self.x = x; self.y = y; self.w = w; self.h = h; self.alpha = alpha
        }
    }

    public struct Screen: Equatable, Sendable {
        public var x, y, w, h: Double
        public init(x: Double, y: Double, w: Double, h: Double) { self.x = x; self.y = y; self.w = w; self.h = h }
    }

    /// The window of a live screenshot: owned by screencaptureui / Screenshot, visible, and either the floating
    /// thumbnail (small, at a screen's bottom-right corner) or the markup window (a real window, not the
    /// full-screen selection overlay of ⌘⇧4, not the thin ⌘⇧5 toolbar).
    public static func isShot(_ w: Window, screens: [Screen]) -> Bool {
        guard owners.contains(w.owner), w.alpha > 0, w.w >= 40, w.h >= 30 else { return false }
        if screens.contains(where: { w.w >= $0.w * 0.9 && w.h >= $0.h * 0.9 }) { return false }
        let thumbnail = screens.contains { s in
            w.w < s.w / 3 && w.h < s.h / 3
                && abs((s.x + s.w) - (w.x + w.w)) <= edge && abs((s.y + s.h) - (w.y + w.h)) <= edge
        }
        return thumbnail || (w.w >= markupMin.w && w.h >= markupMin.h)
    }

    public static func live(_ windows: [Window], screens: [Screen]) -> Bool {
        windows.contains { isShot($0, screens: screens) }
    }
}

/// live / gone transitions of one state (the first observation only primes: nothing was announced before).
public struct LiveEdge: Sendable {
    public private(set) var live: Bool?
    public init(_ initial: Bool? = nil) { live = initial }

    /// "live" when it appears, "gone" when it disappears, nil otherwise.
    public mutating func update(_ now: Bool) -> String? {
        defer { live = now }
        guard let was = live, was != now else { return nil }
        return now ? "live" : "gone"
    }
}

extension AWEvent {
    /// {"kind": "shot_state", "state": "live" | "gone", "src": "thumbnail" | "clipboard"}.
    public static func shotState(at t: Date, state: String, src: String) -> AWEvent {
        AWEvent(timestamp: t, data: ["kind": .string("shot_state"), "state": .string(state), "src": .string(src)])
    }
}
